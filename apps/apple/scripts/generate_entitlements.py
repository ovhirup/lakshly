#!/usr/bin/env python3
"""Generate deterministic Swift gates from the canonical shared entitlement manifest."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / 'packages/shared/entitlements.json'
DEST = ROOT / 'apps/apple/Lakshly/Store/Entitlements.gen.swift'

def render(raw):
    data = json.loads(raw)
    lines = ['// Generated by scripts/generate_entitlements.py. Do not edit.',
             'enum GeneratedEntitlements {',
             f'  static let sourceSHA256 = "{hashlib.sha256(raw).hexdigest()}"',
             '  static let features: [String: FeatureSpec] = [']
    for key, spec in sorted(data['features'].items()):
        limits = ', '.join(f'.{tier}: .{"unlimited" if value is None else f"count({value})"}'
                           for tier, value in sorted(spec.get('limits', {}).items()))
        lines.append(f'    {json.dumps(key)}: FeatureSpec(minTier: .{spec["minTier"]}, limits: [{limits or ":"}]),')
    return '\n'.join(lines + ['  ]', '}', ''])

if __name__ == '__main__':
    DEST.write_text(render(SOURCE.read_bytes()))
